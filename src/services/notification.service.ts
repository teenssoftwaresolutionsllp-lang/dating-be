import { initializeApp, getApps, cert, applicationDefault } from "firebase-admin/app";
import { getMessaging, type SendResponse } from "firebase-admin/messaging";
import fs from "node:fs";
import path from "node:path";
import { db } from "../db/index";
import { userDevices, users } from "../db/schema";
import { eq, and, isNull, inArray } from "drizzle-orm";

let isFirebaseInitialized = false;

// Initialize Firebase Admin safely using modular SDK (firebase-admin v14+)
if (!getApps().length) {
  try {
    if (process.env.FIREBASE_SERVICE_ACCOUNT_PATH) {
      const resolvedPath = path.resolve(process.cwd(), process.env.FIREBASE_SERVICE_ACCOUNT_PATH);
      if (fs.existsSync(resolvedPath)) {
        const fileContent = fs.readFileSync(resolvedPath, "utf-8");
        const serviceAccount = JSON.parse(fileContent);
        initializeApp({
          credential: cert(serviceAccount),
        });
        isFirebaseInitialized = true;
        console.log("🔥 Firebase Admin initialized successfully from service account file.");
      } else {
        console.warn(`[NotificationService] Service account file not found at: ${resolvedPath}`);
      }
    } else if (process.env.FIREBASE_SERVICE_ACCOUNT) {
      const serviceAccount = JSON.parse(process.env.FIREBASE_SERVICE_ACCOUNT);
      initializeApp({
        credential: cert(serviceAccount),
      });
      isFirebaseInitialized = true;
      console.log("🔥 Firebase Admin initialized successfully from FIREBASE_SERVICE_ACCOUNT env.");
    } else if (process.env.GOOGLE_APPLICATION_CREDENTIALS) {
      initializeApp({
        credential: applicationDefault(),
      });
      isFirebaseInitialized = true;
      console.log("🔥 Firebase Admin initialized successfully via applicationDefault.");
    } else {
      console.info(
        "ℹ️ [NotificationService] Firebase credentials not configured. Push notifications will be logged/mocked until credentials are provided."
      );
    }
  } catch (err) {
    console.warn("⚠️ [NotificationService] Failed to initialize Firebase Admin:", err);
  }
} else {
  isFirebaseInitialized = true;
}

export interface SendCallPushNotificationParams {
  receiverId: string;
  callerName: string;
  callType: string; // 'audio' | 'video'
  channelName: string;
  callId: string;
  callerAvatar?: string | null;
}

/**
 * Checks whether a token is an Expo Push Token (generated by Expo Go / Expo push client)
 */
function isExpoPushToken(token: string): boolean {
  return (
    typeof token === "string" &&
    (token.startsWith("ExponentPushToken[") || token.startsWith("ExpoPushToken["))
  );
}

interface ExpoPushMessage {
  to: string;
  title: string;
  body: string;
  data?: Record<string, any>;
  sound?: "default" | null;
  priority?: "default" | "normal" | "high";
  channelId?: string;
}

/**
 * Sends push notifications directly via the Expo HTTP Push API.
 * This works natively without requiring Firebase credentials on the backend.
 */
async function sendExpoPushNotifications(messages: ExpoPushMessage[]): Promise<void> {
  if (!messages.length) return;

  try {
    const res = await fetch("https://exp.host/--/api/v2/push/send", {
      method: "POST",
      headers: {
        Accept: "application/json",
        "Accept-Encoding": "gzip, deflate",
        "Content-Type": "application/json",
      },
      body: JSON.stringify(messages),
    });

    const result = (await res.json()) as {
      data?: Array<{ status: string; message?: string; details?: { error?: string } }>;
    };

    if (result.data && Array.isArray(result.data)) {
      const invalidTokens: string[] = [];
      result.data.forEach((ticket, idx) => {
        if (ticket.status === "error") {
          console.warn(
            `[NotificationService] Expo push error for token ${messages[idx].to}:`,
            ticket.message,
            ticket.details
          );
          if (ticket.details?.error === "DeviceNotRegistered") {
            invalidTokens.push(messages[idx].to);
          }
        }
      });

      if (invalidTokens.length > 0) {
        await db
          .delete(userDevices)
          .where(inArray(userDevices.deviceToken, invalidTokens))
          .catch((cleanupErr) =>
            console.warn("[NotificationService] Expo token cleanup failed:", cleanupErr)
          );
      }
    }
    console.log(`[NotificationService] Sent ${messages.length} Expo push notification(s).`);
  } catch (err) {
    console.warn("[NotificationService] Failed to send Expo push notifications:", err);
  }
}

/**
 * Dispatches an incoming call push notification to all active devices registered to receiverId.
 * Supports both Expo push tokens (Expo Go / client) and native FCM tokens (production APKs).
 */
export async function sendCallPushNotification({
  receiverId,
  callerName,
  callType,
  channelName,
  callId,
  callerAvatar,
}: SendCallPushNotificationParams): Promise<void> {
  try {
    const devices = await db
      .select({ pushToken: userDevices.deviceToken })
      .from(userDevices)
      .innerJoin(users, eq(users.id, userDevices.userId))
      .where(
        and(
          eq(userDevices.userId, receiverId),
          eq(users.status, "active"),
          isNull(userDevices.revokedAt)
        )
      );

    if (!devices.length) {
      console.log(`[NotificationService] No push devices registered for receiver ${receiverId}`);
      return;
    }

    const tokens = devices.map((d) => d.pushToken).filter(Boolean);
    if (!tokens.length) return;

    const expoTokens = tokens.filter(isExpoPushToken);
    const fcmTokens = tokens.filter((t) => !isExpoPushToken(t));

    // 1. Dispatch to Expo devices (always works, even without Firebase on backend)
    if (expoTokens.length > 0) {
      const expoMessages: ExpoPushMessage[] = expoTokens.map((token) => ({
        to: token,
        title: "Incoming Call",
        body: `${callerName} wants to connect with you via ${callType} call.`,
        sound: "default",
        priority: "high",
        channelId: "calls",
        data: {
          type: "INCOMING_CALL",
          recipientId: receiverId,
          callId,
          channelName,
          callType,
          callerName: callerName || "Match",
          callerAvatar: callerAvatar || "",
        },
      }));
      await sendExpoPushNotifications(expoMessages);
    }

    // 2. Dispatch to native FCM devices (production APK / standalone builds)
    if (fcmTokens.length > 0) {
      if (!isFirebaseInitialized) {
        console.log(
          `[NotificationService] (Mock Push) Incoming ${callType} call from "${callerName}" to user ${receiverId} across ${fcmTokens.length} FCM device(s).`
        );
        return;
      }

      const response = await getMessaging().sendEachForMulticast({
        tokens: fcmTokens,
        notification: {
          title: "Incoming Call",
          body: `${callerName} wants to connect with you via ${callType} call.`,
        },
        data: {
          type: "INCOMING_CALL",
          recipientId: receiverId,
          callId,
          channelName,
          callType,
          callerName: callerName || "Match",
          callerAvatar: callerAvatar || "",
        },
        android: {
          priority: "high",
          notification: {
            channelId: "calls",
            sound: "default",
            priority: "high",
          },
        },
        apns: {
          headers: {
            "apns-priority": "10",
          },
          payload: {
            aps: {
              sound: "default",
              badge: 1,
              contentAvailable: true,
            },
          },
        },
      });

      // Cleanup stale or invalid FCM tokens only
      if (response.failureCount > 0) {
        const invalidTokens: string[] = [];
        response.responses.forEach((resp: SendResponse, idx: number) => {
          if (!resp.success && resp.error) {
            const errCode = resp.error.code;
            if (
              errCode === "messaging/invalid-registration-token" ||
              errCode === "messaging/registration-token-not-registered"
            ) {
              invalidTokens.push(fcmTokens[idx]);
            }
          }
        });

        if (invalidTokens.length > 0) {
          await db
            .delete(userDevices)
            .where(inArray(userDevices.deviceToken, invalidTokens))
            .catch((cleanupErr) =>
              console.warn("[NotificationService] FCM token cleanup failed:", cleanupErr)
            );
        }
      }

      console.log(
        `[NotificationService] Call push notification dispatched to FCM: ${response.successCount} succeeded, ${response.failureCount} failed.`
      );
    }
  } catch (err) {
    console.warn("[NotificationService] Failed to dispatch call push notification:", err);
  }
}

/**
 * Generic push notification sender for messages, likes, and matches
 */
export async function sendPushNotification({
  userId,
  title,
  body,
  data = {},
}: {
  userId: string;
  title: string;
  body: string;
  data?: Record<string, string>;
}): Promise<void> {
  try {
    const devices = await db
      .select({ pushToken: userDevices.deviceToken })
      .from(userDevices)
      .innerJoin(users, eq(users.id, userDevices.userId))
      .where(
        and(
          eq(userDevices.userId, userId),
          eq(users.status, "active"),
          isNull(userDevices.revokedAt)
        )
      );

    if (!devices.length) return;

    const tokens = devices.map((d) => d.pushToken).filter(Boolean);
    if (!tokens.length) return;

    const enrichedData: Record<string, string> = {
      ...data,
      recipientId: userId,
    };

    const expoTokens = tokens.filter(isExpoPushToken);
    const fcmTokens = tokens.filter((t) => !isExpoPushToken(t));

    // 1. Dispatch to Expo devices
    if (expoTokens.length > 0) {
      const expoMessages: ExpoPushMessage[] = expoTokens.map((token) => ({
        to: token,
        title,
        body,
        sound: "default",
        priority: "high",
        channelId: "default",
        data: enrichedData,
      }));
      await sendExpoPushNotifications(expoMessages);
    }

    // 2. Dispatch to native FCM devices
    if (fcmTokens.length > 0) {
      if (!isFirebaseInitialized) {
        console.log(`[NotificationService] (Mock Push) to ${userId}: ${title} - ${body}`);
        return;
      }

      await getMessaging().sendEachForMulticast({
        tokens: fcmTokens,
        notification: {
          title,
          body,
        },
        data: enrichedData,
        android: {
          priority: "high",
          notification: {
            channelId: "default",
            sound: "default",
          },
        },
        apns: {
          payload: {
            aps: {
              sound: "default",
              badge: 1,
            },
          },
        },
      });
    }
  } catch (err) {
    console.warn("[NotificationService] Failed to send push notification:", err);
  }
}
